// «г. Москва!» → «москва»: lower case, ё → е, no «г.» / «город», one space for any
// run of spaces, dashes and dots.
export function normalize(text) {
  return String(text || '').toLowerCase().replace(/ё/gu, 'е')
    .replace(/^\s*(?:город\s|гор\.|г\.|г\s)\s*/u, '')
    .replace(/[-–—_.]+/gu, ' ')
    .replace(/[^\p{L}\p{N} ]+/gu, '')
    .replace(/\s+/gu, ' ')
    .trim();
}

const INDEX = new Map();
for (const [name, lat, lon, ...more] of CITIES) {
  const city = { name, lat, lon };
  for (const k of [name, ...more]) INDEX.set(normalize(k), city);
}

export const cityCount = CITIES.length;

// «Москва, Россия», «г. Питер», «Химки (Подмосковье)» → { name, lat, lon }, or null.
export function findCity(text) {
  const whole = normalize(text);
  if (!whole) return null;
  if (INDEX.has(whole)) return INDEX.get(whole);
  const head = normalize(String(text).split(/[,(/|;]/u)[0]);
  return INDEX.get(head) || null;
}
