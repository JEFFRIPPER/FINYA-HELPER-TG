export const GENERATED = TEMPLATES.reduce((s, t) => s + t.count, 0);

function gcd(a, b) { return b ? gcd(b, a % b) : a; }
let STRIDE = 7919;
while (gcd(STRIDE, GENERATED) !== 1) STRIDE += 2;

// n in [0, GENERATED) → [question, options]; distinct n give distinct questions.
export function questionAt(n) {
  let k = (n * STRIDE + 13) % GENERATED;
  for (const t of TEMPLATES) {
    if (k < t.count) return t.make(k);
    k -= t.count;
  }
  throw new Error('question index out of range');
}
