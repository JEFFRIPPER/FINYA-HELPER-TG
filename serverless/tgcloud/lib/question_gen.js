const up = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// Unordered pairs i < j of a list: k → [i, j].
function pairCount(n) { return (n * (n - 1)) / 2; }
function pairAt(n, k) {
  let i = 0;
  while (k >= n - 1 - i) { k -= n - 1 - i; i += 1; }
  return [i, i + 1 + k];
}

